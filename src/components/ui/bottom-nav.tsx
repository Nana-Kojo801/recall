export function BottomNav() {
  const { pathname } = useLocation();
  const navigate = useNavigate();

  return (
    <div
      className="md:hidden fixed bottom-4 left-4 right-4 z-40 flex justify-around items-center px-1 py-2 rounded-full"
      style={{
        background: "#fff",
        border: "2.5px solid #1C1917",
        boxShadow: "4px 4px 0 #1C1917",
      }}
    >
      {NAV.map((n) => {
        const active = n.exact ? pathname === n.path : pathname === n.path || pathname.startsWith(n.path + "/");
        return (
          <button
            key={n.id}
            onClick={() => navigate(n.path)}
            className="flex items-center justify-center px-3 py-2 rounded-full transition-colors duration-150"
            style={{
              background: active ? "#1C1917" : "transparent",
              color: active ? "#F5EFE2" : "#8A8278",
            }}
          >
            {n.icon(active)}
          </button>
        );
      })}
    </div>
  );
}
